def symbol(key, rows):
    n = max(len(r) for r in rows)
    dots = ""
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == "#":
                dots += f'<rect x="{x}" y="{y}" width="1" height="1"/>'
    return (f'<symbol id="i-{key}" viewBox="0 0 {n} {len(rows)}">'
            f'<g fill="currentColor">{dots}</g></symbol>')


def main():
    body = "".join(symbol(k, v) for k, v in ART.items())
    svg = ('<svg xmlns="http://www.w3.org/2000/svg" style="display:none" '
           'aria-hidden="true">' + body + '</svg>\n')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(svg)
    print(f"✅ ドット絵アイコン {len(ART)} 種を書き出しました: assets/img/cat-icons.svg")


if __name__ == "__main__":
    main()
